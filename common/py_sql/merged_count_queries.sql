/*
Merged linking-study count and correlation queries.

Expected table-name template variables (the Python runner renders these as
Snowflake string literals before execution):
  $MERGED_TABLE_NAME
  $PARTNER_TABLE_NAME
  $MAP_GROWTH_TABLE_NAME
  $SETTINGS_TABLE_NAME

Each -- RESULT_SET marker identifies one Excel worksheet produced by
run_merged_counts_queries.py. Keep each result query self-contained so it can
also be copied and run independently after setting the four variables above.
*/

-- RESULT_SET: Study Summary
-------------------------------------------------------------------
-- Partner / MAP / merged counts and percents per study.
-- MAP counts use test name only (no grade qualification).
-------------------------------------------------------------------
WITH settings AS (
    SELECT DISTINCT
        SETTINGS_STUDY_TYPE,
        SETTINGS_D_SUBJECT,
        SETTINGS_D_MAPGROWTH_TEST_NAME,
        SETTINGS_STUDY_GRADES
    FROM IDENTIFIER($SETTINGS_TABLE_NAME)
),

settings_grades AS (
    SELECT
        s.SETTINGS_STUDY_TYPE,
        s.SETTINGS_D_SUBJECT,
        s.SETTINGS_D_MAPGROWTH_TEST_NAME,
        TRIM(g.VALUE::VARCHAR) AS GRADE
    FROM settings s,
         LATERAL FLATTEN(SPLIT(s.SETTINGS_STUDY_GRADES, ',')) g
),

partner_counts AS (
    SELECT
        sg.SETTINGS_STUDY_TYPE,
        sg.SETTINGS_D_SUBJECT,
        sg.SETTINGS_D_MAPGROWTH_TEST_NAME,
        COUNT(p.D_SUBJECT) AS PARTNER_TEST_COUNT
    FROM settings_grades sg
    LEFT JOIN IDENTIFIER($PARTNER_TABLE_NAME) p
        ON p.D_SUBJECT = sg.SETTINGS_D_SUBJECT
       AND TRIM(p.D_GRADE::VARCHAR) = sg.GRADE
    GROUP BY 1, 2, 3
),

map_counts AS (
    SELECT
        s.SETTINGS_STUDY_TYPE,
        s.SETTINGS_D_SUBJECT,
        s.SETTINGS_D_MAPGROWTH_TEST_NAME,
        COUNT(m.TEST_NAME) AS MAP_TEST_COUNT
    FROM settings s
    LEFT JOIN IDENTIFIER($MAP_GROWTH_TABLE_NAME) m
        ON m.TEST_NAME = s.SETTINGS_D_MAPGROWTH_TEST_NAME
    GROUP BY 1, 2, 3
),

merged_counts AS (
    SELECT
        sg.SETTINGS_STUDY_TYPE,
        sg.SETTINGS_D_SUBJECT,
        sg.SETTINGS_D_MAPGROWTH_TEST_NAME,
        COUNT(mc.D_SUBJECT) AS MERGED_TEST_COUNT,
        CORR(mc.M_IRIT, mc.D_SS) AS CORRELATION
    FROM settings_grades sg
    LEFT JOIN IDENTIFIER($MERGED_TABLE_NAME) mc
        ON mc.D_SUBJECT = sg.SETTINGS_D_SUBJECT
       AND mc.M_TEST_NAME = sg.SETTINGS_D_MAPGROWTH_TEST_NAME
       AND TRIM(mc.D_GRADE::VARCHAR) = sg.GRADE
       AND mc.MATCH_TYPE <> 'UNMATCHED'
    GROUP BY 1, 2, 3
)

SELECT
    p.SETTINGS_STUDY_TYPE,
    p.SETTINGS_D_SUBJECT,
    p.SETTINGS_D_MAPGROWTH_TEST_NAME,
    p.PARTNER_TEST_COUNT,
    ROUND(mc.MERGED_TEST_COUNT / NULLIF(p.PARTNER_TEST_COUNT, 0), 4) AS PARTNER_PERCENT_MERGED,
    m.MAP_TEST_COUNT,
    ROUND(mc.MERGED_TEST_COUNT / NULLIF(m.MAP_TEST_COUNT, 0), 4) AS MAP_PERCENT_MERGED,
    mc.MERGED_TEST_COUNT,
    ROUND(
        mc.MERGED_TEST_COUNT
        / NULLIF(LEAST(p.PARTNER_TEST_COUNT, m.MAP_TEST_COUNT), 0),
        4
    ) AS MERGE_RATE,
    ROUND(mc.CORRELATION, 4) AS CORRELATION
FROM partner_counts p
LEFT JOIN map_counts m
    ON m.SETTINGS_STUDY_TYPE = p.SETTINGS_STUDY_TYPE
   AND m.SETTINGS_D_SUBJECT = p.SETTINGS_D_SUBJECT
   AND m.SETTINGS_D_MAPGROWTH_TEST_NAME = p.SETTINGS_D_MAPGROWTH_TEST_NAME
LEFT JOIN merged_counts mc
    ON mc.SETTINGS_STUDY_TYPE = p.SETTINGS_STUDY_TYPE
   AND mc.SETTINGS_D_SUBJECT = p.SETTINGS_D_SUBJECT
   AND mc.SETTINGS_D_MAPGROWTH_TEST_NAME = p.SETTINGS_D_MAPGROWTH_TEST_NAME
ORDER BY 1, 2, 3;


