SELECT
    p.SETTINGS_D_SUBJECT,
    p.SETTINGS_D_MAPGROWTH_TEST_NAME,
    p.AGENCY_CODE,
    COALESCE(dn.M_DISTRICT_STANDARD_NAME, mdn.DISTRICT_STANDARD_NAME) AS M_DISTRICT_STANDARD_NAME,
    p.PARTNER_TEST_COUNT,
    ROUND(
        COALESCE(mc.MERGED_TEST_COUNT, 0)
        / NULLIF(p.PARTNER_TEST_COUNT, 0),
        4
    ) AS PARTNER_PERCENT_MERGED,
    COALESCE(m.MAP_TEST_COUNT, 0) AS MAP_TEST_COUNT,
    ROUND(
        COALESCE(mc.MERGED_TEST_COUNT, 0)
        / NULLIF(m.MAP_TEST_COUNT, 0),
        4
    ) AS MAP_PERCENT_MERGED,
    COALESCE(mc.MERGED_TEST_COUNT, 0) AS MERGED_TEST_COUNT,
    ROUND(
        COALESCE(mc.MERGED_TEST_COUNT, 0)
        / NULLIF(
            LEAST(p.PARTNER_TEST_COUNT, COALESCE(m.MAP_TEST_COUNT, 0)),
            0
        ),
        4
    ) AS MERGE_RATE,
    ROUND(mc.CORRELATION, 4) AS CORRELATION
FROM partner_counts p
LEFT JOIN map_counts m
    ON m.SETTINGS_D_SUBJECT = p.SETTINGS_D_SUBJECT
   AND m.SETTINGS_D_MAPGROWTH_TEST_NAME = p.SETTINGS_D_MAPGROWTH_TEST_NAME
   AND m.AGENCY_CODE = p.AGENCY_CODE
LEFT JOIN merged_counts mc
    ON mc.SETTINGS_D_SUBJECT = p.SETTINGS_D_SUBJECT
   AND mc.SETTINGS_D_MAPGROWTH_TEST_NAME = p.SETTINGS_D_MAPGROWTH_TEST_NAME
   AND mc.AGENCY_CODE = p.AGENCY_CODE
LEFT JOIN district_names dn
    ON dn.AGENCY_CODE = p.AGENCY_CODE
LEFT JOIN map_district_names mdn
    ON mdn.AGENCY_CODE = p.AGENCY_CODE
WHERE p.PARTNER_TEST_COUNT > 0
ORDER BY 1, 2, 3;


-- RESULT_SET: Study Grade Agency
-------------------------------------------------------------------
-- Partner / MAP / merged counts and percents by study, grade,
-- and agency.
-- Agency columns:
--   partner = D_AGENCYCODE
--   MAP     = DISTRICT_AGENCY_CODE
--   merged  = D_AGENCYCODE
-------------------------------------------------------------------
WITH settings AS (
    SELECT DISTINCT
        SETTINGS_STUDY_TYPE,
        SETTINGS_D_SUBJECT,
        SETTINGS_D_MAPGROWTH_TEST_NAME,
        SETTINGS_STUDY_GRADES
    FROM IDENTIFIER($SETTINGS_TABLE_NAME)
),

settings_grades AS (
    SELECT
        s.SETTINGS_STUDY_TYPE,
        s.SETTINGS_D_SUBJECT,
        s.SETTINGS_D_MAPGROWTH_TEST_NAME,
        TRIM(g.VALUE::VARCHAR) AS GRADE
    FROM settings s,
         LATERAL FLATTEN(SPLIT(s.SETTINGS_STUDY_GRADES, ',')) g
),

partner_counts AS (
    SELECT
        sg.SETTINGS_STUDY_TYPE,
        sg.SETTINGS_D_SUBJECT,
        sg.SETTINGS_D_MAPGROWTH_TEST_NAME,
        sg.GRADE,
        TRIM(p.D_AGENCYCODE::VARCHAR) AS AGENCY_CODE,
        COUNT(p.D_SUBJECT) AS PARTNER_TEST_COUNT
    FROM settings_grades sg
    JOIN IDENTIFIER($PARTNER_TABLE_NAME) p
        ON p.D_SUBJECT = sg.SETTINGS_D_SUBJECT
       AND TRIM(p.D_GRADE::VARCHAR) = sg.GRADE
    GROUP BY 1, 2, 3, 4, 5
),

map_counts AS (
    SELECT
        sg.SETTINGS_STUDY_TYPE,
        sg.SETTINGS_D_SUBJECT,
        sg.SETTINGS_D_MAPGROWTH_TEST_NAME,
        sg.GRADE,
        TRIM(m.DISTRICT_AGENCY_CODE::VARCHAR) AS AGENCY_CODE,
        COUNT(m.TEST_NAME) AS MAP_TEST_COUNT
    FROM settings_grades sg
    JOIN IDENTIFIER($MAP_GROWTH_TABLE_NAME) m
        ON m.TEST_NAME = sg.SETTINGS_D_MAPGROWTH_TEST_NAME
       AND TRIM(m.GRADE_ORDINAL::VARCHAR) = sg.GRADE
    GROUP BY 1, 2, 3, 4, 5
),

merged_counts AS (
    SELECT
        sg.SETTINGS_STUDY_TYPE,
        sg.SETTINGS_D_SUBJECT,
        sg.SETTINGS_D_MAPGROWTH_TEST_NAME,
        sg.GRADE,
        TRIM(mc.D_AGENCYCODE::VARCHAR) AS AGENCY_CODE,
        COUNT(mc.D_SUBJECT) AS MERGED_TEST_COUNT,
        CORR(mc.M_IRIT, mc.D_SS) AS CORRELATION
    FROM settings_grades sg
    JOIN IDENTIFIER($MERGED_TABLE_NAME) mc
        ON mc.D_SUBJECT = sg.SETTINGS_D_SUBJECT
       AND mc.M_TEST_NAME = sg.SETTINGS_D_MAPGROWTH_TEST_NAME
       AND TRIM(mc.D_GRADE::VARCHAR) = sg.GRADE
       AND mc.MATCH_TYPE <> 'UNMATCHED'
    GROUP BY 1, 2, 3, 4, 5
),

keys AS (
    SELECT
        SETTINGS_STUDY_TYPE,
        SETTINGS_D_SUBJECT,
        SETTINGS_D_MAPGROWTH_TEST_NAME,
        GRADE,
        AGENCY_CODE
    FROM partner_counts

    UNION

    SELECT
        SETTINGS_STUDY_TYPE,
        SETTINGS_D_SUBJECT,
        SETTINGS_D_MAPGROWTH_TEST_NAME,
        GRADE,
        AGENCY_CODE
    FROM map_counts

    UNION

    SELECT
        SETTINGS_STUDY_TYPE,
        SETTINGS_D_SUBJECT,
        SETTINGS_D_MAPGROWTH_TEST_NAME,
        GRADE,
        AGENCY_CODE
    FROM merged_counts
),

district_names AS (
    SELECT
        TRIM(M_DISTRICT_AGENCY_CODE::VARCHAR) AS AGENCY_CODE,
        ANY_VALUE(M_DISTRICT_STANDARD_NAME) AS M_DISTRICT_STANDARD_NAME
    FROM IDENTIFIER($MERGED_TABLE_NAME)
    WHERE M_DISTRICT_AGENCY_CODE IS NOT NULL
      AND M_DISTRICT_STANDARD_NAME IS NOT NULL
    GROUP BY 1
),

map_district_names AS (
    SELECT
        TRIM(DISTRICT_AGENCY_CODE::VARCHAR) AS AGENCY_CODE,
        ANY_VALUE(DISTRICT_STANDARD_NAME) AS DISTRICT_STANDARD_NAME
    FROM IDENTIFIER($MAP_GROWTH_TABLE_NAME)
    WHERE DISTRICT_AGENCY_CODE IS NOT NULL
    GROUP BY 1
)

SELECT
    k.SETTINGS_STUDY_TYPE,
    k.SETTINGS_D_SUBJECT,
    k.SETTINGS_D_MAPGROWTH_TEST_NAME,
    k.GRADE,
    k.AGENCY_CODE,
    COALESCE(dn.M_DISTRICT_STANDARD_NAME, mdn.DISTRICT_STANDARD_NAME) AS M_DISTRICT_STANDARD_NAME,
    COALESCE(p.PARTNER_TEST_COUNT, 0) AS PARTNER_TEST_COUNT,
    ROUND(
        COALESCE(mc.MERGED_TEST_COUNT, 0)
        / NULLIF(p.PARTNER_TEST_COUNT, 0),
        4
    ) AS PARTNER_PERCENT_MERGED,
    COALESCE(m.MAP_TEST_COUNT, 0) AS MAP_TEST_COUNT,
    ROUND(
        COALESCE(mc.MERGED_TEST_COUNT, 0)
        / NULLIF(m.MAP_TEST_COUNT, 0),
        4
    ) AS MAP_PERCENT_MERGED,
    COALESCE(mc.MERGED_TEST_COUNT, 0) AS MERGED_TEST_COUNT,
    ROUND(
        COALESCE(mc.MERGED_TEST_COUNT, 0)
        / NULLIF(
            LEAST(
                COALESCE(p.PARTNER_TEST_COUNT, 0),
                COALESCE(m.MAP_TEST_COUNT, 0)
            ),
            0
        ),
        4
    ) AS MERGE_RATE,
    ROUND(mc.CORRELATION, 4) AS CORRELATION
FROM keys k
LEFT JOIN partner_counts p
    ON p.SETTINGS_STUDY_TYPE = k.SETTINGS_STUDY_TYPE
   AND p.SETTINGS_D_SUBJECT = k.SETTINGS_D_SUBJECT
   AND p.SETTINGS_D_MAPGROWTH_TEST_NAME = k.SETTINGS_D_MAPGROWTH_TEST_NAME
   AND p.GRADE = k.GRADE
   AND p.AGENCY_CODE IS NOT DISTINCT FROM k.AGENCY_CODE
LEFT JOIN map_counts m
    ON m.SETTINGS_STUDY_TYPE = k.SETTINGS_STUDY_TYPE
   AND m.SETTINGS_D_SUBJECT = k.SETTINGS_D_SUBJECT
   AND m.SETTINGS_D_MAPGROWTH_TEST_NAME = k.SETTINGS_D_MAPGROWTH_TEST_NAME
   AND m.GRADE = k.GRADE
   AND m.AGENCY_CODE IS NOT DISTINCT FROM k.AGENCY_CODE
LEFT JOIN merged_counts mc
    ON mc.SETTINGS_STUDY_TYPE = k.SETTINGS_STUDY_TYPE
   AND mc.SETTINGS_D_SUBJECT = k.SETTINGS_D_SUBJECT
   AND mc.SETTINGS_D_MAPGROWTH_TEST_NAME = k.SETTINGS_D_MAPGROWTH_TEST_NAME
   AND mc.GRADE = k.GRADE
   AND mc.AGENCY_CODE IS NOT DISTINCT FROM k.AGENCY_CODE
LEFT JOIN district_names dn
    ON dn.AGENCY_CODE = k.AGENCY_CODE
LEFT JOIN map_district_names mdn
    ON mdn.AGENCY_CODE = k.AGENCY_CODE
WHERE p.PARTNER_TEST_COUNT > 0
ORDER BY
    k.SETTINGS_STUDY_TYPE,
    k.SETTINGS_D_SUBJECT,
    k.SETTINGS_D_MAPGROWTH_TEST_NAME,
    TRY_TO_NUMBER(k.GRADE) NULLS FIRST,
    k.GRADE,
    M_DISTRICT_STANDARD_NAME,
    k.AGENCY_CODE;
