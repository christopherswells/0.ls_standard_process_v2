        s.SETTINGS_D_SUBJECT,
        s.SETTINGS_D_MAPGROWTH_TEST_NAME,
        TRIM(p.D_AGENCYCODE::VARCHAR) AS AGENCY_CODE,
        COUNT(p.D_SUBJECT) AS PARTNER_TEST_COUNT
    FROM settings s
    JOIN IDENTIFIER($PARTNER_TABLE_NAME) p
        ON p.D_SUBJECT = s.SETTINGS_D_SUBJECT
    GROUP BY 1, 2, 3
),

map_counts AS (
    SELECT
        s.SETTINGS_D_SUBJECT,
        s.SETTINGS_D_MAPGROWTH_TEST_NAME,
        TRIM(m.DISTRICT_AGENCY_CODE::VARCHAR) AS AGENCY_CODE,
        COUNT(m.TEST_NAME) AS MAP_TEST_COUNT
    FROM settings s
    JOIN IDENTIFIER($MAP_GROWTH_TABLE_NAME) m
        ON m.TEST_NAME = s.SETTINGS_D_MAPGROWTH_TEST_NAME
    GROUP BY 1, 2, 3
),

merged_counts AS (
    SELECT
        s.SETTINGS_D_SUBJECT,
        s.SETTINGS_D_MAPGROWTH_TEST_NAME,
        TRIM(mc.D_AGENCYCODE::VARCHAR) AS AGENCY_CODE,
        COUNT(mc.D_SUBJECT) AS MERGED_TEST_COUNT,
        CORR(mc.M_IRIT, mc.D_SS) AS CORRELATION
    FROM settings s
    JOIN IDENTIFIER($MERGED_TABLE_NAME) mc
        ON mc.D_SUBJECT = s.SETTINGS_D_SUBJECT
       AND mc.M_TEST_NAME = s.SETTINGS_D_MAPGROWTH_TEST_NAME
       AND mc.MATCH_TYPE <> 'UNMATCHED'
    GROUP BY 1, 2, 3
),

district_names AS (
    SELECT
        TRIM(M_DISTRICT_AGENCY_CODE::VARCHAR) AS AGENCY_CODE,
        ANY_VALUE(M_DISTRICT_STANDARD_NAME) AS M_DISTRICT_STANDARD_NAME
    FROM IDENTIFIER($MERGED_TABLE_NAME)
    WHERE M_DISTRICT_AGENCY_CODE IS NOT NULL
      AND M_DISTRICT_STANDARD_NAME IS NOT NULL
    GROUP BY 1
