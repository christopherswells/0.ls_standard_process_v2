-- RESULT_SET: Subject Agency
-------------------------------------------------------------------
-- Partner / MAP / merged counts, percents, and IRIT~D_SS
-- correlation by subject and agency across all grades.
-- Agency columns:
--   partner = D_AGENCYCODE
--   MAP     = DISTRICT_AGENCY_CODE
--   merged  = D_AGENCYCODE
-------------------------------------------------------------------
WITH settings AS (
    SELECT DISTINCT
        SETTINGS_D_SUBJECT,
        SETTINGS_D_MAPGROWTH_TEST_NAME
    FROM IDENTIFIER($SETTINGS_TABLE_NAME)
),

partner_counts AS (
